"""Start lichess-bot with a chosen kind of games to look for (bullet / blitz / rapid / mixed).

Run with the lichess-bot venv (start_bot.bat does this):
    lichess-bot\\venv\\Scripts\\python.exe start_bot.py [bullet|blitz|rapid|fast|mixed|none]

Reads lichess-bot/config.yml, writes lichess-bot/config_run.yml with the matchmaking section
set for the chosen mode and starts `lichess-bot.py --config config_run.yml`.

Matchmaking speed: lichess-bot creates the next challenge `challenge_timeout` minutes after a
game ends (it enforces a minimum of 1 minute) and at most one challenge per 60 seconds
(Lichess API rate limits). Here: 1 minute, and bots that declined are not challenged again
with the same kind of challenge (challenge_filter: coarse), so fewer attempts are wasted.
While a game is running no challenges are sent (concurrency 1, allow_during_games false).
Incoming challenges are still accepted according to the `challenge` section of config.yml.

The API token is never written anywhere: it comes from the LICHESS_BOT_TOKEN environment
variable, from config.yml, or is asked for here and passed only to the lichess-bot process.
"""
import getpass
import os
import subprocess
import sys
from pathlib import Path

import yaml

# (base seconds, increment seconds); Lichess speed = base + 40 * increment:
# bullet < 180 s, blitz < 480 s, rapid < 1500 s
MODES = {
    "bullet": ("Пуля", [(60, 0), (60, 1), (120, 1)]),
    "blitz": ("Блиц", [(180, 0), (180, 2), (300, 0), (300, 3)]),
    "rapid": ("Рапид", [(600, 0), (600, 5), (900, 10)]),
}
MODES["fast"] = ("Пуля + блиц", MODES["bullet"][1] + MODES["blitz"][1])
MODES["mixed"] = ("Всё вперемешку", MODES["bullet"][1] + MODES["blitz"][1] + MODES["rapid"][1])
MENU = [("1", "bullet"), ("2", "blitz"), ("3", "rapid"), ("4", "fast"), ("5", "mixed"), ("6", "none")]


def describe(tcs):
    return ", ".join(f"{b // 60}+{i}" for b, i in tcs)


def choose_mode(argv):
    if len(argv) > 1:
        mode = argv[1].lower()
        if mode in MODES or mode == "none":
            return mode
        print(f"Неизвестный режим '{argv[1]}'. Варианты: bullet, blitz, rapid, fast, mixed, none.")
    print()
    print("Какие партии бот будет искать сам?")
    for key, mode in MENU:
        if mode == "none":
            print(f"  {key} — не искать, только принимать вызовы")
        else:
            name, tcs = MODES[mode]
            print(f"  {key} — {name} ({describe(tcs)})")
    while True:
        try:
            answer = input("Выбор [1-6]: ").strip()
        except EOFError:
            answer = "5"
        for key, mode in MENU:
            if answer == key or answer.lower() == mode:
                return mode
        print("Введите число от 1 до 6.")


def user_env_token():
    """LICHESS_BOT_TOKEN from the Windows user environment (set with SetEnvironmentVariable ... "User"),
    which processes started before it was set do not inherit."""
    try:
        import winreg

        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment") as key:
            value, _ = winreg.QueryValueEx(key, "LICHESS_BOT_TOKEN")
            return str(value).strip()
    except (ImportError, OSError):
        return ""


def matchmaking_section(base, mode):
    mm = dict(base or {})
    if mode == "none":
        mm["allow_matchmaking"] = False
        return mm
    tcs = MODES[mode][1]
    mm["allow_matchmaking"] = True
    mm["allow_during_games"] = False
    mm["challenge_timeout"] = 1  # minutes after a game; lichess-bot does not allow less
    mm["challenge_filter"] = "coarse"
    mm.setdefault("challenge_variant", "standard")
    # default spec = first time control, overrides = the others: lichess-bot picks one at random
    mm["challenge_initial_time"] = [tcs[0][0]]
    mm["challenge_increment"] = [tcs[0][1]]
    mm.pop("challenge_days", None)
    mm["overrides"] = {
        f"tc_{b // 60}_{i}": {"challenge_initial_time": [b], "challenge_increment": [i]} for b, i in tcs[1:]
    }
    return mm


def main():
    root = Path(__file__).resolve().parent / "lichess-bot"
    config_path = root / "config.yml"
    if not config_path.exists():
        print(f"Не найден {config_path}. Сначала настройте lichess-bot (см. deploy/README.md).")
        return 1
    with config_path.open(encoding="utf-8") as f:
        config = yaml.safe_load(f)

    mode = choose_mode(sys.argv)
    config["matchmaking"] = matchmaking_section(config.get("matchmaking"), mode)
    # one game at a time: when a game is found the bot stops looking until it ends
    config.setdefault("challenge", {})["concurrency"] = 1

    run_path = root / "config_run.yml"
    with run_path.open("w", encoding="utf-8") as f:
        f.write("# Generated by deploy/start_bot.py - edit config.yml instead.\n")
        yaml.safe_dump(config, f, allow_unicode=True, sort_keys=False)

    env = dict(os.environ)
    token_in_config = str(config.get("token", ""))
    if not env.get("LICHESS_BOT_TOKEN"):
        env_token = user_env_token()
        if env_token:
            env["LICHESS_BOT_TOKEN"] = env_token
    if not env.get("LICHESS_BOT_TOKEN") and (not token_in_config or token_in_config.startswith("set-")):
        if not sys.stdin.isatty():
            print("Нет токена: задайте переменную LICHESS_BOT_TOKEN (см. deploy/README.md).")
            return 1
        token = getpass.getpass("API-токен Lichess (ввод скрыт, никуда не сохраняется): ").strip()
        if not token:
            print("Токен не введён.")
            return 1
        env["LICHESS_BOT_TOKEN"] = token

    if mode == "none":
        print("\nРежим: без поиска, бот только принимает вызовы.")
    else:
        name, tcs = MODES[mode]
        print(f"\nРежим: {name} ({describe(tcs)}). Новый вызов — через 1 минуту после партии,")
        print("дальше не чаще раза в минуту, пока кто-то не примет. Остановка: Ctrl+C.")
    print()
    proc = subprocess.Popen([sys.executable, "lichess-bot.py", "--config", "config_run.yml"], cwd=root, env=env)
    try:
        return proc.wait()
    except KeyboardInterrupt:
        # lichess-bot handles Ctrl+C itself (finishes or aborts the current game)
        return proc.wait()


if __name__ == "__main__":
    sys.exit(main())
