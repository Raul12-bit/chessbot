//! Texel tuning of the linear evaluation in `evalt.rs`.
//! Loss: mean squared error between game result and sigmoid(K * eval / 400) (base-10 logistic).
//! Optimizer: full-batch Adam over sparse feature traces, multi-threaded gradient.

use crate::board::Board;
use crate::eval_params::P;
use crate::evalt::{eval_impl, N_PARAMS};
use std::fs::File;
use std::io::{BufRead, BufReader, Write};
use std::time::Instant;

struct Data {
    feats: Vec<(u16, i16)>,
    offsets: Vec<u32>, // len = n + 1
    phase: Vec<u8>,
    result: Vec<f32>,
}

impl Data {
    fn len(&self) -> usize {
        self.result.len()
    }
}

fn load(path: &str, limit: usize) -> Option<Data> {
    let f = File::open(path).ok()?;
    let mut d = Data { feats: Vec::new(), offsets: vec![0], phase: Vec::new(), result: Vec::new() };
    let mut tr = vec![0i16; N_PARAMS];
    let mut max_err = 0i32;
    for line in BufReader::new(f).lines().map_while(Result::ok) {
        if d.len() >= limit {
            break;
        }
        let mut parts = line.split('|');
        let (Some(fen), Some(res)) = (parts.next(), parts.next()) else { continue };
        let Ok(res) = res.trim().parse::<f32>() else { continue };
        let Ok(b) = Board::from_fen(fen.trim()) else { continue };
        tr.iter_mut().for_each(|x| *x = 0);
        let (mg, eg, phase) = eval_impl::<true>(&b, &mut tr);
        // sanity: the linear model must reproduce the engine eval
        let (mut lmg, mut leg) = (0i32, 0i32);
        for (i, &c) in tr.iter().enumerate() {
            if c != 0 {
                d.feats.push((i as u16, c));
                lmg += P[i].0 * c as i32;
                leg += P[i].1 * c as i32;
            }
        }
        max_err = max_err.max((lmg - mg).abs()).max((leg - eg).abs());
        d.offsets.push(d.feats.len() as u32);
        d.phase.push(phase as u8);
        d.result.push(res);
    }
    if max_err != 0 {
        eprintln!("WARNING: linear model mismatch {max_err}");
    }
    Some(d)
}

#[inline(always)]
fn sigmoid(e: f64, k: f64) -> f64 {
    1.0 / (1.0 + 10f64.powf(-k * e / 400.0))
}

#[inline(always)]
fn lin_eval(d: &Data, i: usize, w: &[[f64; 2]]) -> f64 {
    let (mut mg, mut eg) = (0.0, 0.0);
    for &(idx, c) in &d.feats[d.offsets[i] as usize..d.offsets[i + 1] as usize] {
        let c = c as f64;
        mg += w[idx as usize][0] * c;
        eg += w[idx as usize][1] * c;
    }
    let ph = d.phase[i] as f64;
    (mg * ph + eg * (24.0 - ph)) / 24.0
}

fn error(d: &Data, w: &[[f64; 2]], k: f64, threads: usize) -> f64 {
    let n = d.len();
    let chunk = n.div_ceil(threads);
    let total: f64 = std::thread::scope(|s| {
        let hs: Vec<_> = (0..threads)
            .map(|t| {
                s.spawn(move || {
                    let mut e = 0.0;
                    for i in t * chunk..((t + 1) * chunk).min(n) {
                        let diff = d.result[i] as f64 - sigmoid(lin_eval(d, i, w), k);
                        e += diff * diff;
                    }
                    e
                })
            })
            .collect();
        hs.into_iter().map(|h| h.join().unwrap_or(0.0)).sum()
    });
    total / n as f64
}

fn gradient(d: &Data, w: &[[f64; 2]], k: f64, threads: usize) -> Vec<[f64; 2]> {
    let n = d.len();
    let chunk = n.div_ceil(threads);
    let parts: Vec<Vec<[f64; 2]>> = std::thread::scope(|s| {
        let hs: Vec<_> = (0..threads)
            .map(|t| {
                s.spawn(move || {
                    let mut g = vec![[0.0f64; 2]; N_PARAMS];
                    for i in t * chunk..((t + 1) * chunk).min(n) {
                        let sg = sigmoid(lin_eval(d, i, w), k);
                        let r = d.result[i] as f64;
                        // d(err)/d(eval)
                        let de = -2.0 * (r - sg) * sg * (1.0 - sg) * std::f64::consts::LN_10 * k / 400.0;
                        let ph = d.phase[i] as f64 / 24.0;
                        for &(idx, c) in &d.feats[d.offsets[i] as usize..d.offsets[i + 1] as usize] {
                            let c = c as f64 * de;
                            g[idx as usize][0] += c * ph;
                            g[idx as usize][1] += c * (1.0 - ph);
                        }
                    }
                    g
                })
            })
            .collect();
        hs.into_iter().map(|h| h.join().unwrap_or_default()).collect()
    });
    let mut g = vec![[0.0f64; 2]; N_PARAMS];
    for p in parts {
        for (a, b) in g.iter_mut().zip(p.iter()) {
            a[0] += b[0] / n as f64;
            a[1] += b[1] / n as f64;
        }
    }
    g
}

fn write_params(path: &str, w: &[[f64; 2]]) -> std::io::Result<()> {
    let mut f = File::create(path)?;
    writeln!(f, "//! Evaluation parameters (mg, eg). Layout: see `evalt.rs`. Generated by `chessbot tune`.\n")?;
    writeln!(f, "#[rustfmt::skip]\npub const P: [(i32, i32); {N_PARAMS}] = [")?;
    for row in w.chunks(8) {
        let s: Vec<String> =
            row.iter().map(|p| format!("({}, {}),", p[0].round() as i32, p[1].round() as i32)).collect();
        writeln!(f, "    {}", s.join(" "))?;
    }
    writeln!(f, "];")?;
    Ok(())
}

pub fn run(data_path: &str, out: &str, epochs: usize, limit: usize, threads: usize) {
    let t0 = Instant::now();
    let Some(d) = load(data_path, limit) else {
        eprintln!("cannot load {data_path}");
        return;
    };
    eprintln!("loaded {} positions ({} features) in {:.1}s", d.len(), d.feats.len(), t0.elapsed().as_secs_f64());
    if d.len() == 0 {
        return;
    }
    let mut w: Vec<[f64; 2]> = P.iter().map(|&(a, b)| [a as f64, b as f64]).collect();
    // L2 regularization towards the starting values: keeps rarely seen features
    // (e.g. queen mobility 25+) from drifting to extreme values.
    let w0 = w.clone();
    let lambda: f64 = std::env::var("TUNE_L2").ok().and_then(|v| v.parse().ok()).unwrap_or(5e-10);

    // fit K for the initial parameters (golden-section search)
    let (mut lo, mut hi) = (0.3f64, 3.0f64);
    let gr = (5f64.sqrt() - 1.0) / 2.0;
    for _ in 0..30 {
        let a = hi - gr * (hi - lo);
        let b = lo + gr * (hi - lo);
        if error(&d, &w, a, threads) < error(&d, &w, b, threads) {
            hi = b;
        } else {
            lo = a;
        }
    }
    let k = (lo + hi) / 2.0;
    eprintln!("K = {k:.4}, initial error {:.6}", error(&d, &w, k, threads));

    let (b1, b2, eps) = (0.9f64, 0.999f64, 1e-8f64);
    let mut m = vec![[0.0f64; 2]; N_PARAMS];
    let mut v = vec![[0.0f64; 2]; N_PARAMS];
    for epoch in 1..=epochs {
        let lr = if epoch < epochs / 2 { 1.0 } else { 0.4 };
        let mut g = gradient(&d, &w, k, threads);
        for i in 0..N_PARAMS {
            for j in 0..2 {
                g[i][j] += 2.0 * lambda * (w[i][j] - w0[i][j]);
            }
        }
        for i in 0..N_PARAMS {
            for j in 0..2 {
                m[i][j] = b1 * m[i][j] + (1.0 - b1) * g[i][j];
                v[i][j] = b2 * v[i][j] + (1.0 - b2) * g[i][j] * g[i][j];
                let mh = m[i][j] / (1.0 - b1.powi(epoch as i32));
                let vh = v[i][j] / (1.0 - b2.powi(epoch as i32));
                w[i][j] -= lr * mh / (vh.sqrt() + eps);
            }
        }
        // king material is meaningless; keep it at zero
        w[5] = [0.0, 0.0];
        if epoch % 100 == 0 || epoch == epochs {
            eprintln!("epoch {epoch} error {:.6} ({:.0}s)", error(&d, &w, k, threads), t0.elapsed().as_secs_f64());
            if let Err(e) = write_params(out, &w) {
                eprintln!("write failed: {e}");
            }
        }
    }
    eprintln!("done, params written to {out}");
}
